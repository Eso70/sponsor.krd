export function useCampaignText() {
  const { locale } = usePlatformLocale();
  return useCallback((source: string) => campaignText(source, locale), [locale]);
}

export function campaignText(source: string, locale: PlatformLocale) {
  return locale === "ar"
    ? ARABIC_TEXT[source] ?? source
    : locale === "en"
      ? ENGLISH_TEXT[source] ?? source
      : KURDISH_TEXT[source] ?? source;
}
