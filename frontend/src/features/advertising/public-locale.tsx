export function PublicAdvertisingLocaleProvider({ locale, children }: { locale: BusinessLocale; children: ReactNode }) {
  return <AdvertisingLocaleContext.Provider value={locale}>{children}</AdvertisingLocaleContext.Provider>;
}

export function usePublicAdvertisingLocale() {
  return useContext(AdvertisingLocaleContext);
}

export function usePublicAdvertisingText() {
  const locale = usePublicAdvertisingLocale();
  return (text: string) => translatePublicAdvertisingText(text, locale);
}

export function translatePublicAdvertisingText(text: string, locale: BusinessLocale): string {
  return locale === "ar" ? arabicPublicAdvertisingCopy[text] ?? text : locale === "en" ? englishPublicAdvertisingCopy[text] ?? text : text;
}
